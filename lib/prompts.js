// สุ่มองค์ประกอบคลิป โดยเลี่ยงค่าที่ใช้ในคลิปล่าสุดของสินค้านี้ (lastUsed = องค์ประกอบของคลิปก่อน)
function pickVariation(lastUsed = {}) {
  const pick = (key) => {
    const pool = CLIP_VARIATIONS[key].filter((v) => !(lastUsed[key] || []).includes(v));
    const list = pool.length ? pool : CLIP_VARIATIONS[key];
    return list[Math.floor(Math.random() * list.length)];
  };
  return Object.fromEntries(Object.keys(CLIP_VARIATIONS).map((k) => [k, pick(k)]));
}

function fillTemplate(tpl, vars) {
  return tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] ?? '').toString() || '-');
}

// ส่วนต่อท้ายคำสั่งวางแผน (สไตล์ + ความเป็นมนุษย์ + สิ่งที่ห้ามซ้ำ) ต่อแยกจาก template
// เพื่อให้ใช้ได้แม้ผู้ใช้เคยบันทึก template เวอร์ชันเก่าไว้ในหน้าตั้งค่า
function planExtras({ style, variation, humanGuide, avoid, companion, text }) {
  const parts = [`สไตล์คลิปรอบนี้: "${style.label}" — ${style.guide}`];
  if (variation) {
    // สไตล์ที่กำหนดฉากเอง (เช่น โฆษณามืออาชีพ) ไม่ใช้สถานที่/แสงที่สุ่ม
    parts.push(
      'องค์ประกอบของคลิปรอบนี้ (สุ่มมาเพื่อไม่ให้ซ้ำกับคลิปก่อน ๆ ใช้ตามนี้):\n' +
        (style.fixedScene ? '' : `- สถานที่/ฉาก: ${variation.location}\n`) +
        `- ผู้นำเสนอ: ${variation.persona}\n` +
        `- บทเปิด 3 วินาทีแรก: ${variation.hook}\n` +
        `- ภาษากล้อง: ${variation.camera}` +
        (style.fixedScene ? '' : `\n- แสง/บรรยากาศ: ${variation.mood}`)
    );
  }
  if (text) parts.push(textPlanBlock(text));
  if (companion) parts.push(companion);
  if (humanGuide) parts.push(humanGuide);
  if (avoid?.length) {
    parts.push(
      'คลิปของสินค้านี้เคยใช้บทเปิด/มุมเล่าเรื่องต่อไปนี้แล้ว รอบนี้ต้องคิดใหม่ให้ต่างออกไป (ฉาก มุมกล้อง บทพูด และแคปชัน ห้ามซ้ำหรือคล้าย):\n' +
        avoid.map((a) => `- ${a}`).join('\n')
    );
  }
  // คำเหล่านี้ใน video prompt ทำให้ Flow ปฏิเสธเรื่อง "บุคคลที่มีชื่อเสียง" ได้ง่าย
  parts.push(
    "ใน video_prompt ห้ามใช้คำว่า fictional, celebrity, famous, real person, lookalike, identity หรือ reference person " +
      "ให้เรียกผู้นำเสนอว่า 'the woman in the image' หรือ 'the presenter' เท่านั้น และบรรยายแค่ท่าทาง การเคลื่อนไหว กล้อง และแสง"
  );
  return parts.join('\n\n');
}

